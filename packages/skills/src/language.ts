/** English or Indonesian by function words; "unknown" when neither leads or fewer than `least` were found. A token with a digit in it (an id, a hash) is not a word, so its letters never count. */
export function languageOf(text: string, least = 3): Language | "unknown" {
  let en = 0, id = 0;
  for (const word of text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []) { if (EN.has(word)) en++; if (ID.has(word)) id++; }
  return en + id < least || en === id ? "unknown" : en > id ? "en" : "id";
}

/** The language messages clearly read as, or undefined when they show none. Chat is short, so two function words decide. */
export const shownLanguage = (...texts: (string | null | undefined)[]): Language | undefined => {
  const language = languageOf(texts.filter(Boolean).join("\n"), 2);
  return language === "unknown" ? undefined : language;
};
/** The language for the bot's own text about these messages: the one they read as, English when they show none. */
export const replyLanguage = (...texts: (string | null | undefined)[]): Language => shownLanguage(...texts) ?? "en";

export const DEFAULT_LANGUAGE: Language = "id";
export const isLanguage = (value: unknown): value is Language => value === "id" || value === "en";
/** Each language's name in English, for instructions to a model. */
export const LANGUAGE_NAME: Record<Language, string> = { en: "English", id: "Indonesian" };
/** The language for text the bot writes with no message to detect from (Digest, Reminder framing, provider errors): the guild's override, else the tenant's. */
export const configuredLanguage = (...levels: ({ language?: string | null } | null | undefined)[]): Language => levels.map((l) => l?.language).find(isLanguage) ?? DEFAULT_LANGUAGE;

